def normalize_query_question(question: str) -> str:
    """归一化用户问题，减少口语别名对路由与 SQL 生成的影响。"""
    normalized = WHITESPACE_RE.sub(" ", (question or "").strip())
    for raw, canonical in TYPO_ALIAS_MAP.items():
        if raw == "切坡":
            normalized = re.sub(r"(?<!高)切坡", canonical, normalized)
        else:
            normalized = normalized.replace(raw, canonical)
    normalized = normalized.replace("高高切坡", "高切坡")
    for raw, canonical in REGION_ALIAS_MAP.items():
        normalized = normalized.replace(raw, canonical)
    return normalized
